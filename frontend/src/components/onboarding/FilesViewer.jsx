import { useState } from 'react';
import { Icon } from '../common/Icon.jsx';

// what "validated before deploy" means (validate.service.js): shown on hover
const VALIDATED =
  'Before anything is built or deployed, Kairo parses every file it wrote and checks the parts the rest of Kairo relies on: names and namespace, the app port and PORT setting, health checks, the memory limit and the alert names. A file that fails stops the run at the Generating step, before the build.';

const ICON = {
  DOCKERFILE: 'description',
  DEPLOYMENT: 'deployed_code',
  SERVICE: 'lan',
  INGRESS: 'route',
  WORKFLOW: 'account_tree',
  ALERT_RULES: 'notifications_active',
};

// The files Kairo generated, one tab each, with line numbers and a copy button
export function FilesViewer({ files }) {
  const [active, setActive] = useState(0);
  const [copied, setCopied] = useState(false);
  const file = files[Math.min(active, files.length - 1)];
  const lines = file.content.replace(/\n$/, '').split('\n');

  async function copy() {
    try {
      await navigator.clipboard.writeText(file.content);
      setCopied(true);
      setTimeout(() => setCopied(false), 1500);
    } catch {
      // ignore: clipboard blocked
    }
  }

  return (
    <section className="rounded border border-outline-variant bg-surface-container-low" aria-label="Generated files">
      <div className="flex items-end justify-between gap-2 border-b border-outline-variant pr-2">
        <div role="tablist" className="flex min-w-0 overflow-x-auto">
          {files.map((f, i) => (
            <button
              key={f.path}
              role="tab"
              type="button"
              aria-selected={i === active}
              onClick={() => setActive(i)}
              className={`flex shrink-0 items-center gap-1.5 border-b-2 px-3 py-2.5 font-mono text-code-md ${
                i === active ? 'border-primary text-primary' : 'border-transparent text-on-surface-variant hover:text-on-surface'
              }`}
            >
              <Icon name={ICON[f.kind] ?? 'description'} className="text-[16px]" />
              {f.path}
              {f.origin === 'KEPT_EXISTING' && (
                <span className="rounded border border-outline-variant px-1 text-code-sm text-on-surface-variant">kept</span>
              )}
            </button>
          ))}
        </div>
        <button type="button" onClick={copy} className="mb-1.5 inline-flex shrink-0 items-center gap-1 rounded border border-outline-variant px-2 py-1 font-mono text-code-sm text-on-surface-variant hover:text-on-surface">
          <Icon name={copied ? 'check' : 'content_copy'} className="text-[16px]" />
          {copied ? 'Copied' : 'Copy'}
        </button>
      </div>
      <pre role="tabpanel" className="max-h-[480px] overflow-auto bg-surface-container-lowest p-3 font-mono text-code-md leading-5">
        {lines.map((line, i) => (
          <div key={i} className="flex">
            <span className="w-10 shrink-0 select-none pr-3 text-right text-outline">{i + 1}</span>
            <span className="whitespace-pre">{line}</span>
          </div>
        ))}
      </pre>
      <div className="border-t border-outline-variant px-3 py-2 font-mono text-code-sm text-on-surface-variant">
        {file.origin === 'GENERATED' ? (
          <span title={VALIDATED} className="cursor-help underline decoration-dotted underline-offset-2">
            Generated by Kairo · validated before deploy
          </span>
        ) : (
          "Kept from the repo: Kairo builds it as it is and leaves it out of the PR"
        )}
      </div>
    </section>
  );
}
