// The setup PR's text (FR-32): the stack, each fact with its source, every
// assumption, the files, and that Trivy is report-only. Pure, so it's tested
// without GitHub.

export const SETUP_BRANCH = 'kairo/setup';
export const PR_TITLE = 'Set up Kairo: Dockerfile, Kubernetes, CI and alert rules';
// lets Kairo recognise its own PR body
export const PR_MARKER = '<!-- kairo:setup -->';

const FACT_LABELS = {
  stack: 'Stack',
  dockerfile: 'Dockerfile',
  packageManager: 'Package manager',
  nodeVersion: 'Node version',
  pythonVersion: 'Python version',
  buildScript: 'Build',
  startCommand: 'Start command',
  testScript: 'Tests',
  port: 'Port',
};

const FILE_NOTES = {
  DOCKERFILE: 'Builds the image',
  DEPLOYMENT: 'Kubernetes Deployment: probes, 256Mi memory limit, `PORT`',
  SERVICE: 'Kubernetes Service (ClusterIP, traffic comes through Traefik)',
  INGRESS: 'Routes `<slug>.kairo.local` to the app',
  WORKFLOW: 'Builds amd64 + arm64 images and pushes them to GHCR on every push',
  ALERT_RULES: 'Prometheus alert rules Kairo heals from',
};

const code = (v) => `\`${String(v).replace(/`/g, "'")}\``;
const cell = (v) => String(v).replace(/\|/g, '\\|').replace(/\n/g, ' ');

/**
 * @param {{ repoFullName: string, defaultBranch: string, commitSha: string, image: string,
 *           files: { kind: string, origin: string, path: string }[],
 *           facts: Record<string, { value: any, source: string, from: string }>,
 *           assumptions: string[], graceSeconds: number }} p
 */
export function prBody(p) {
  const sha = p.commitSha.slice(0, 7);
  const kept = p.files.filter((f) => f.origin === 'KEPT_EXISTING');
  const added = p.files.filter((f) => f.origin !== 'KEPT_EXISTING');

  const facts = Object.entries(p.facts ?? {}).map(
    ([key, f]) => `| ${FACT_LABELS[key] ?? key} | ${code(f.value)} | ${f.source}: ${cell(f.from)} |`,
  );

  const lines = [
    `Kairo deployed a preview of ${code(sha)} and it stayed healthy through its ${p.graceSeconds} s grace window, so these are the files it used. Merge this PR and every push to ${code(p.defaultBranch)} is built by GitHub Actions and rolled out by Kairo.`,
    '',
    '### What Kairo detected',
    '',
    '| Fact | Value | Source |',
    '| --- | --- | --- |',
    ...facts,
    '',
    '`rule` means Kairo read it from the repo; `default` means Kairo had nothing to read and used its default.',
    '',
  ];

  if (p.assumptions?.length) {
    lines.push('### Assumptions', '', ...p.assumptions.map((a) => `- ${a}`), '');
  }

  lines.push('### Files in this PR', '', '| File | What it does |', '| --- | --- |');
  for (const f of added) lines.push(`| ${code(f.path)} | ${FILE_NOTES[f.kind] ?? ''} |`);
  lines.push('');
  if (kept.length) {
    lines.push(
      `**Kept as they are:** ${kept.map((f) => code(f.path)).join(', ')}. The repo already had ${kept.length === 1 ? 'it' : 'them'}, so Kairo builds ${kept.length === 1 ? 'it' : 'them'} unchanged and leaves ${kept.length === 1 ? 'it' : 'them'} out of this PR.`,
      '',
    );
  }

  lines.push(
    '### Good to know',
    '',
    `- Images go to ${code(p.image)}, tagged with the full commit sha. No secrets to add: the workflow uses its own \`GITHUB_TOKEN\`.`,
    '- **Trivy is report-only.** It scans every image and lists findings in the workflow log, but never fails the build.',
    '- Every action in the workflow is pinned to a commit SHA, not a tag, so it can\'t change under you.',
    '- Other workflow files in the repo are untouched. Edit these files freely: Kairo builds whatever the merged workflow produces.',
    '',
    PR_MARKER,
  );
  return lines.join('\n');
}

export function commitMessage(commitSha) {
  return `Add Kairo setup files\n\nGenerated by Kairo from the healthy preview of ${commitSha.slice(0, 7)}.`;
}
